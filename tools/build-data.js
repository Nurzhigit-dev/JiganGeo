/**
 * The plain reference card for a country: capital, money, size, who it touches.
 * mledoze/countries carries everything except population, which comes from the
 * World Bank so the figure is current rather than whatever year the static
 * dataset was frozen at.
 */
// Entities that ISO 3166 does not list (so mledoze has no row) and territories
// the World Bank does not report on. Figures are round approximations, and the
// UI does not claim otherwise.
const MANUAL_INFO = {
  XKX: {
    capital: 'Pristina', currency: { code: 'EUR', name: 'Euro', symbol: '€' },
    area: 10887, languages: ['Albanian', 'Serbian'], phone: '+383',
    population: 1600000, popYear: '2024 est.', borders: ['ALB', 'MKD', 'MNE', 'SRB'],
    landlocked: true,
  },
  XNC: {
    capital: 'North Nicosia', currency: { code: 'TRY', name: 'Turkish lira', symbol: '₺' },
    area: 3355, languages: ['Turkish'], phone: '+90',
    population: 390000, popYear: '2024 est.', borders: ['CYP'], landlocked: false,
  },
  XSO: {
    capital: 'Hargeisa', currency: { code: 'SLS', name: 'Somaliland shilling', symbol: 'Sl' },
    area: 176120, languages: ['Somali', 'Arabic', 'English'], phone: '+252',
    population: 5700000, popYear: '2024 est.', borders: ['DJI', 'ETH', 'SOM'],
    landlocked: false,
  },
};
// Populations the World Bank does not publish
const MANUAL_POP = {
  TWN: { value: 23400000, year: '2025 est.' },
  ESH: { value: 600000, year: '2024 est.' },
  FLK: { value: 3700, year: '2021 census' },
};

function buildCountryInfo(worldFC) {
  const src = read('countries-mledoze.json');
  const byCca3 = new Map(src.map(c => [c.cca3, c]));

  const wb = read('worldbank-pop.json')[1] || [];
  const pop = new Map();
  for (const row of wb) {
    if (row.countryiso3code && row.value) {
      pop.set(row.countryiso3code, { value: Math.round(row.value), year: row.date });
    }
  }

  const out = {};
  const missing = [];
  for (const f of worldFC.features) {
    const id = f.properties.id;
    if (MANUAL_INFO[id]) { out[id] = MANUAL_INFO[id]; continue; }
    const c = byCca3.get(id);
    if (!c) { missing.push(f.properties.name); continue; }

    const cur = Object.entries(c.currencies || {})[0];
    const p = pop.get(id) || MANUAL_POP[id];
    const entry = {
      capital: (c.capital && c.capital[0]) || null,
      currency: cur ? { code: cur[0], name: cur[1].name, symbol: cur[1].symbol || '' } : null,
      area: c.area || null,
      languages: Object.values(c.languages || {}),
      tld: (c.tld && c.tld[0]) || null,
      borders: c.borders || [],
      landlocked: !!c.landlocked,
    };
    if (p) { entry.population = p.value; entry.popYear = p.year; }
    if (c.idd && c.idd.root) {
      entry.phone = c.idd.root + ((c.idd.suffixes && c.idd.suffixes.length === 1) ? c.idd.suffixes[0] : '');
    }
    out[id] = entry;
  }
  if (missing.length) console.warn('  ! no reference data for: ' + missing.join(', '));
  const noPop = Object.keys(out).filter(k => !out[k].population);
  if (noPop.length) console.warn('  ! no population for: ' + noPop.join(', '));

  emit('countries.js', 'DATA_COUNTRY_INFO', out);
  return out;
}

/* ----------------------------------------------------------------- CITIES */
const G = { name: 1, ascii: 2, lat: 4, lon: 5, fcode: 7, country: 8, pop: 14 };

function haversine(a, b) {
  const R = 6371, rad = d => d * Math.PI / 180;
  const dLat = rad(b.lat - a.lat), dLon = rad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
    + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

function buildCities(japanFC, franceDepFC) {
  const lines = fs.readFileSync(path.join(RAW, 'jpfr.txt'), 'utf8').split('\n').filter(Boolean);
  // GeoNames column 1 keeps diacritics (Nîmes, Besançon); column 2 is stripped
  // ASCII, which we keep only for accent-insensitive matching.
  const RENAME = { 'Nara-shi': 'Nara', 'Dunkirk': 'Dunkerque' };
  const rows = lines.map(l => l.split('\t')).map(c => ({
    name: RENAME[c[G.name]] || c[G.name],
    ascii: c[G.ascii],
    lat: +c[G.lat], lon: +c[G.lon],
    fcode: c[G.fcode], country: c[G.country], pop: +c[G.pop],
  }));

  // Tokyo's special wards and the big-city "-shi" duplicates are separate rows
  // in GeoNames; they would stack on top of each other on a city map.
  const DENY = new Set(['Shinjuku', 'Shibuya', 'Chiyoda', 'Chuo', 'Minato', 'Taito', 'Sumida',
    'Koto', 'Shinagawa', 'Meguro', 'Ota', 'Setagaya', 'Nakano', 'Suginami', 'Toshima', 'Kita',
    'Arakawa', 'Itabashi', 'Nerima', 'Adachi', 'Katsushika', 'Edogawa', 'Bunkyo', 'Ōta',
    'Yokohama Shi', 'Osaka Shi', 'Nagoya Shi', 'Sakai Shi', 'Marne La Vallee', 'Marne La Vallée',
    'Boulogne-Billancourt', 'Montreuil', 'Argenteuil', 'Saint-Denis', 'Nanterre', 'Vitry-sur-Seine',
    'Créteil', 'Asnières-sur-Seine', 'Courbevoie', 'Colombes', 'Aulnay-sous-Bois', 'Rueil-Malmaison',
    'Champigny-sur-Marne', 'Antony', 'Neuilly-sur-Seine', 'Levallois-Perret', 'Issy-les-Moulineaux',
    'Cergy', 'Pantin', 'Ivry-sur-Seine', 'Clichy', 'Sarcelles', 'Drancy', 'Noisy-le-Grand',
    'Villeurbanne', 'Aubervilliers', 'La Courneuve', 'Épinay-sur-Seine', 'Bobigny',
    'Maisons-Alfort', 'Meaux', 'Chelles', 'Fontenay-sous-Bois', 'Bondy', 'Le Blanc-Mesnil',
    'Sevran', 'Saint-Maur-des-Fossés', 'Vincennes', 'Massy', 'Villejuif', 'Clamart',
    'Bourg-la-Reine', 'Suresnes', 'Puteaux', 'Malakoff', 'Gennevilliers', 'Bagneux',
    // GeoNames duplicates that outrank the city they belong to
    'Aihara', 'Saint-Quentin-en-Yvelines',
  ]);

  // Keep real settlements only: PPLX is a city district, PPLL a loose locality.
  const OK_FCODE = new Set(['PPL', 'PPLA', 'PPLA2', 'PPLA3', 'PPLA4', 'PPLC', 'PPLG']);

  function pick(cc, poly, keyProp, limit, minPop) {
    const cand = rows
      .filter(r => r.country === cc && r.pop >= minPop && OK_FCODE.has(r.fcode)
        && !DENY.has(r.name) && !DENY.has(r.ascii))
      .sort((a, b) => b.pop - a.pop);

    const chosen = [];
    for (const c of cand) {
      if (chosen.length >= limit) break;
      // collapse near-duplicates: one conurbation listed under several names
      if (chosen.some(o => haversine(o, c) < 15)) continue;
      const owner = poly.features.find(f => d3.geoContains(f, [c.lon, c.lat]));
      if (!owner) continue; // offshore, or outside the mapped area
      const entry = {
        name: c.name,
        lat: +c.lat.toFixed(4), lon: +c.lon.toFixed(4), pop: c.pop,
        parent: owner.properties.name,
      };
      entry[keyProp] = owner.properties.id;
      if (c.ascii && c.ascii !== c.name) entry.ascii = c.ascii;
      chosen.push(entry);
    }
    return chosen;
  }

  const jp = pick('JP', japanFC, 'prefecture', 55, 150000);
  const fr = pick('FR', franceDepFC, 'department', 55, 55000);
  emit('cities.js', 'DATA_CITIES', { JP: jp, FR: fr });
  return { jp: jp, fr: fr };
}

