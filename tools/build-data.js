/*
 * build-data.js — turns the raw sources in tools/raw/ into the browser data
 * files in data/. Everything is emitted as `window.DATA_* = ...` so the app
 * works from file:// with no server and no build step.
 *
 * Run with:  node tools/build-data.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const RAW = path.join(__dirname, 'raw');
const OUT = path.join(__dirname, '..', 'data');
const read = f => JSON.parse(fs.readFileSync(path.join(RAW, f), 'utf8'));

// --- load d3-geo + topojson into a clean context (their UMD wrappers take the
// CommonJS branch under node, which breaks the d3-array dependency) ---------
const ctx = vm.createContext({});
for (const f of ['d3-array.min.js', 'd3-geo.min.js', 'topojson-client.min.js'])
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', 'vendor', f), 'utf8'), ctx);
const d3 = ctx.d3, topojson = ctx.topojson;

function emit(file, varName, value) {
  const body = '// Generated by tools/build-data.js — do not edit by hand.\n'
    + 'window.' + varName + ' = ' + JSON.stringify(value) + ';\n';
  fs.writeFileSync(path.join(OUT, file), body);
  console.log('  data/' + file.padEnd(16) + (body.length / 1024).toFixed(0).padStart(5) + ' KB  ' + varName);
}

function round(features, prec) {
  const r = n => Math.round(n * 10 ** prec) / 10 ** prec;
  const walk = c => Array.isArray(c[0]) ? c.map(walk) : [r(c[0]), r(c[1])];
  for (const f of features) f.geometry.coordinates = walk(f.geometry.coordinates);
}

/* ------------------------------------------------------------------ WORLD */
function buildWorld() {
  const topo = read('world-110m.json');
  const fc = topojson.feature(topo, topo.objects.countries);
  const iso = read('iso.json');
  const byNum = new Map(iso.map(r => [String(+r['country-code']), r]));

  // world-atlas abbreviates some names; spell them out for quiz prompts
  const NAME_FIX = {
    'Dem. Rep. Congo': 'DR Congo',
    'Congo': 'Republic of the Congo',
    'Central African Rep.': 'Central African Republic',
    'Dominican Rep.': 'Dominican Republic',
    'Eq. Guinea': 'Equatorial Guinea',
    'S. Sudan': 'South Sudan',
    'Bosnia and Herz.': 'Bosnia and Herzegovina',
    'Solomon Is.': 'Solomon Islands',
    'Falkland Is.': 'Falkland Islands',
    'Fr. S. Antarctic Lands': 'French Southern Territories',
    'W. Sahara': 'Western Sahara',
    'N. Cyprus': 'Northern Cyprus',
    'United States of America': 'United States',
    'Central African Rep': 'Central African Republic',
  };
  // continent info for entries ISO 3166 does not assign
  const EXTRA = {
    'Somaliland': { region: 'Africa', subregion: 'Sub-Saharan Africa', iso2: 'XS', id: 'XSO' },
    'Kosovo': { region: 'Europe', subregion: 'Southern Europe', iso2: 'XK', id: 'XKX' },
    'Northern Cyprus': { region: 'Asia', subregion: 'Western Asia', iso2: 'XN', id: 'XNC' },
  };
  // ISO 3166 leaves Taiwan's region fields blank; the quiz needs a continent
  const REGION_FIX = { TWN: { region: 'Asia', subregion: 'Eastern Asia' } };

  const features = [];
  for (const f of fc.features) {
    const meta = byNum.get(String(+f.id));
    const rawName = f.properties.name;
    const name = NAME_FIX[rawName] || rawName;
    const extra = EXTRA[name];
    if (!meta && !extra) { console.warn('  ! no ISO metadata for ' + rawName); continue; }
    const id = meta ? meta['alpha-3'] : extra.id;
    const fix = REGION_FIX[id];
    features.push({
      type: 'Feature',
      properties: {
        id: id,
        iso2: meta ? meta['alpha-2'] : extra.iso2,
        name: name,
        region: (fix && fix.region) || (meta ? meta.region : extra.region),
        subregion: (fix && fix.subregion) || (meta ? meta['sub-region'] : extra.subregion),
      },
      geometry: f.geometry,
    });
  }
  // Antarctica is not a country-quiz target
  const out = features.filter(f => f.properties.id !== 'ATA');
  round(out, 2);
  out.sort((a, b) => a.properties.name.localeCompare(b.properties.name));
  emit('world.js', 'DATA_WORLD', { type: 'FeatureCollection', features: out });
  return { type: 'FeatureCollection', features: out };
}

